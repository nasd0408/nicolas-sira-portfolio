const html = document.documentElement;
const langButton = document.querySelector(".lang-toggle");
const langLabels = [...document.querySelectorAll("[data-lang]")];
const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
const bandwidth = navigator.connection;
const conserveData = Boolean(bandwidth?.saveData || /(^|-)2g$|^3g$/.test(bandwidth?.effectiveType || ""));
function prepareVideo(video) {
  const sources = [...video.querySelectorAll("source[data-src]")];
  if (!sources.length) return;
  sources.forEach((source) => {
    source.src = source.dataset.src;
    source.removeAttribute("data-src");
  });
  video.load();
}
// Keep distant videos entirely unfetched. On a slow connection, only an explicit play loads them.
if (!conserveData && !reducedMotion) {
  const nearbyVideos = new IntersectionObserver((entries) => {
    entries.forEach(({isIntersecting, target}) => {
      if (!isIntersecting) return;
      target.preload = "metadata";
      prepareVideo(target);
      nearbyVideos.unobserve(target);
    });
  }, {rootMargin: "400px 0px"});
  document.querySelectorAll("video[data-deferred]").forEach(video => nearbyVideos.observe(video));
}
const finePointer = window.matchMedia("(pointer: fine)").matches;
const cursorOrb = document.querySelector(".cursor-orb");
const loader = document.querySelector(".site-loader");
const loaderCount = document.querySelector(".loader-count");

if (loader) {
  const loaderDuration = reducedMotion ? 120 : 650;
  const loaderStartedAt = Date.now();
  let loaderReleased = false;

  const releaseLoader = () => {
    if (loaderReleased) return;
    loaderReleased = true;
    loader.style.setProperty("--loader-progress", "1");
    loaderCount.textContent = "100";
    loader.classList.add("is-leaving");
    html.classList.remove("is-loading");
    const hashTarget = window.location.hash && document.querySelector(window.location.hash);
    if (hashTarget) window.requestAnimationFrame(() => hashTarget.scrollIntoView({ block: "start" }));
    window.setTimeout(() => loader.remove(), reducedMotion ? 20 : 950);
  };

  const loaderTimer = window.setInterval(() => {
    const elapsed = Math.min(1, (Date.now() - loaderStartedAt) / loaderDuration);
    const eased = 1 - Math.pow(1 - elapsed, 3);
    loader.style.setProperty("--loader-progress", eased.toFixed(4));
    loaderCount.textContent = String(Math.round(eased * 100)).padStart(2, "0");

    if (elapsed >= 1) {
      window.clearInterval(loaderTimer);
      window.setTimeout(releaseLoader, reducedMotion ? 0 : 120);
    }
  }, reducedMotion ? 20 : 25);

  window.setTimeout(releaseLoader, loaderDuration + (reducedMotion ? 80 : 650));
} else {
  html.classList.remove("is-loading");
}

function setLanguage(lang) {
  const dictionary = translations[lang] || translations.en;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.innerHTML = value;
  });
  html.lang = lang;
  document.querySelectorAll("[data-cv-link]").forEach((link) => {
    link.href = `assets/cv/Nicolas-Sira-CV-${lang === "es" ? "ES" : "EN"}.pdf`;
  });
  langLabels.forEach((label) => label.classList.toggle("active", label.dataset.lang === lang));
  langButton.setAttribute("aria-pressed", String(lang === "es"));
  localStorage.setItem("nicolas-portfolio-language", lang);
}

